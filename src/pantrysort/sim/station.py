"""Build a Drake station for the pantry scene with an SO-101 arm, and drive it kinematically.

All pydrake imports are inside functions so this module imports cleanly even
when Drake is not installed (the inventory/QR tests don't need it).

The station contains:
  * a TheRobotStudio SO-101 arm (``assets/so101``, Apache-2.0), base welded at
    the world origin facing +x,
  * a conveyor belt running past the front of the arm, carrying open cardboard
    donation boxes (one body each) to the pick station and on past it,
  * one body per ``SceneItem`` (packed in a donation box, or on a flat intake
    mat for box-less scenes), each with a QR sticker,
  * an open category bin with a name sign per storage location, and
  * a Meshcat visualizer (optional).

Motion is *kinematic*: joint angles come from inverse kinematics and are set
directly on the plant context, held items follow the gripper rigidly, and every
frame is published to Meshcat (and recorded, so it can be replayed). There is no
contact-dynamics grasping yet; that can replace ``Station.move_ee_to`` /
``attach_nearest`` later without changing the sort loop.

SO-101 joints (in position order): shoulder_pan, shoulder_lift, elbow_flex,
wrist_flex, wrist_roll, gripper. These names match LeRobot's SO-101 driver, so
joint trajectories from this sim map 1:1 onto the real arm's motor names.
"""

