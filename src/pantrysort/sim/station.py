# Gripper joint angle (rad) -> jaw gap (m) at the grasp depth, measured from the
# SO-101 meshes. Used to close the jaws exactly on each item's width.
_GRIPPER_Q = np.arange(0.0, 1.0, 0.1)
_GRIPPER_GAP = np.array([0.018, 0.024, 0.030, 0.037, 0.043, 0.050, 0.057, 0.065, 0.073, 0.084])
GRIPPER_OPEN = 0.85  # ~7.8 cm gap, clears every apple


def gripper_angle_for_width(width: float) -> float:
    """Gripper joint angle at which the jaws just touch an item of ``width``."""
    return float(np.interp(width, _GRIPPER_GAP, _GRIPPER_Q))


