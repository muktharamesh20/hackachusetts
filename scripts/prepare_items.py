"""Convert the meshes in 3MF files into item OBJs for the Drake scene.

Each mesh object becomes ``assets/items/<prefix>.obj`` (or ``<prefix>_<letter>.obj``
when a file holds several objects), in meters, re-centered on its bounding box
(so an item resting on the table sits at z = height / 2). Every converted shape
is recorded in ``assets/items/shapes.yaml`` (size, mesh, color), which the scene
reads.

Usage:
    PYTHONPATH=src python scripts/prepare_items.py                         # the apples
    PYTHONPATH=src python scripts/prepare_items.py assets/printables/*.3mf
    PYTHONPATH=src python scripts/prepare_items.py some.3mf --prefix pear
"""

from __future__ import annotations

import argparse
import string
from pathlib import Path

import yaml

from pantrysort.sim.mesh_io import read_3mf, write_obj

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT = REPO_ROOT / "assets" / "items"
# The apples file predates the naming convention; keep its historical prefix.
_KNOWN_PREFIXES = {"apples-printable-ppp": "apple"}


def prepare(src: Path, prefix: str | None, out_dir: Path) -> dict[str, dict]:
    meshes = read_3mf(src)
    if not meshes:
        raise SystemExit(f"error: no meshes found in {src}")
    prefix = prefix or _KNOWN_PREFIXES.get(src.stem) or src.stem.replace("-", "_")
    entries: dict[str, dict] = {}
    for letter, mesh in zip(string.ascii_lowercase, meshes, strict=False):
        name = prefix if len(meshes) == 1 else f"{prefix}_{letter}"
        lo, hi = mesh.vertices.min(axis=0), mesh.vertices.max(axis=0)
        write_obj(out_dir / f"{name}.obj", mesh.vertices - (lo + hi) / 2, mesh.faces)
        size = [round(float(s), 5) for s in hi - lo]
        entries[name] = {
            "mesh": f"{name}.obj",
            "size": size,
            "color": [round(c, 3) for c in mesh.color] if mesh.color else None,
            "source": str(src.relative_to(REPO_ROOT) if src.is_relative_to(REPO_ROOT) else src),
        }
        w, d, h = (s * 1000 for s in size)
        print(f"{name:20s} {len(mesh.faces):6d} tris  {w:5.1f} x {d:5.1f} x {h:5.1f} mm")
    return entries


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("src", nargs="*", type=Path,
                        default=[REPO_ROOT / "apples-printable-ppp.3mf"])
    parser.add_argument("--prefix", help="output name (only with a single input file)")
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args(argv)
    if args.prefix and len(args.src) > 1:
        parser.error("--prefix only works with a single input file")

    manifest_path = args.out_dir / "shapes.yaml"
    manifest = {}
    if manifest_path.is_file():
        manifest = yaml.safe_load(manifest_path.read_text(encoding="utf-8")) or {}
    for src in args.src:
        manifest.update(prepare(src.resolve(), args.prefix, args.out_dir))

    args.out_dir.mkdir(parents=True, exist_ok=True)
    header = "# Generated by scripts/prepare_items.py. Sizes are bounding boxes in meters.\n"
    manifest_path.write_text(header + yaml.safe_dump(dict(sorted(manifest.items())),
                                                     sort_keys=False), encoding="utf-8")
    print(f"Updated {manifest_path.relative_to(REPO_ROOT)} ({len(manifest)} shapes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
